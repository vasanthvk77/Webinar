using System.Diagnostics;
using System.Net.Http.Headers;
using System.Text;

namespace WebinarApi.Services;

// -------------------------------------------------------
// TranscriptionService: Pure .NET Groq Whisper Integration
// 1. Splits .webm video into 10-min MP3 chunks using FFmpeg
// 2. Transcribes each chunk using Groq Whisper-large-v3-turbo API
// 3. Merges chunks into a clean .txt transcript file
// 4. Deletes temporary MP3 chunks and the original heavy .webm video
// -------------------------------------------------------
public class TranscriptionService : ITranscriptionService
{
    private readonly IConfiguration _config;
    private readonly ILogger<TranscriptionService> _logger;
    private readonly IHttpClientFactory _httpClientFactory;
    private readonly string _groqApiKey;
    private readonly string _groqApiUrl;
    private readonly string _groqModel;
    private readonly string _groqPrompt;
    private readonly string _recordingStoragePath;

    public TranscriptionService(
        IConfiguration config,
        ILogger<TranscriptionService> logger,
        IHttpClientFactory httpClientFactory)
    {
        _config = config;
        _logger = logger;
        _httpClientFactory = httpClientFactory;

        _groqApiKey = config["Groq:ApiKey"]?.Trim() ?? string.Empty;
        _groqApiUrl = config["Groq:ApiUrl"]?.Trim() ?? "https://api.groq.com/openai/v1/audio/transcriptions";
        _groqModel = config["Groq:Model"]?.Trim() ?? "whisper-large-v3-turbo";
        _groqPrompt = config["Groq:Prompt"]?.Trim() ?? "Webinar presentation, lecture, questions and answers.";
        _recordingStoragePath = config["BBB:RecordingStoragePath"] ?? "../MeetingSources";
    }

    private void LogBoth(string message)
    {
        Console.WriteLine($"[{DateTime.Now:HH:mm:ss} TRANSCRIPT] {message}");
        _logger.LogInformation("{Message}", message);
    }

    private void LogWarnBoth(string message)
    {
        Console.WriteLine($"[{DateTime.Now:HH:mm:ss} WRN] {message}");
        _logger.LogWarning("{Message}", message);
    }

    public async Task<(bool success, string message, string? transcriptRelativePath)> TranscribeVideoAsync(
        string recordId,
        string videoRelativePath,
        CancellationToken cancellationToken = default)
    {
        if (string.IsNullOrWhiteSpace(_groqApiKey))
        {
            LogWarnBoth("[TranscriptionService] ⚠️ Groq API key is NOT configured in appsettings.json ('Groq:ApiKey'). Transcription skipped.");
            return (false, "Groq API key is missing in appsettings.json. Please add your free key from console.groq.com.", null);
        }

        var storageDir = GetAbsoluteStorageDirectory();
        var videoAbsolutePath = Path.IsPathRooted(videoRelativePath)
            ? videoRelativePath
            : Path.GetFullPath(Path.Combine(Directory.GetCurrentDirectory(), videoRelativePath));

        if (!File.Exists(videoAbsolutePath))
        {
            // Also check directly inside storageDir
            var directPath = Path.Combine(storageDir, Path.GetFileName(videoRelativePath));
            if (File.Exists(directPath))
            {
                videoAbsolutePath = directPath;
            }
            else
            {
                LogWarnBoth($"[TranscriptionService] ❌ Video file not found at '{videoAbsolutePath}'.");
                return (false, $"Video file not found: {videoRelativePath}", null);
            }
        }

        // Isolated unique temporary chunk directory for this specific transcription job
        var uniqueJobId = Guid.NewGuid().ToString("N")[..8];
        var chunkDir = Path.Combine(storageDir, $"{recordId}_chunks_{uniqueJobId}");
        var transcriptFileName = $"{recordId}.txt";
        var transcriptAbsolutePath = Path.Combine(storageDir, transcriptFileName);
        var transcriptRelativePath = Path.Combine("MeetingSources", transcriptFileName).Replace('\\', '/');

        try
        {
            // 1. Split video into 10-minute MP3 segments using FFmpeg
            LogBoth($"[TranscriptionService] 🚀 Starting transcription pipeline for RecordId '{recordId}' (Job: {uniqueJobId})...");
            LogBoth($"[TranscriptionService] ✂️ Splitting audio into 10-minute chunks using FFmpeg for RecordId '{recordId}'...");
            var splitSuccess = await SplitAudioWithFfmpegAsync(videoAbsolutePath, chunkDir, cancellationToken);
            if (!splitSuccess)
            {
                return (false, "FFmpeg failed to split audio. Make sure FFmpeg is installed and added to PATH.", null);
            }

            var chunkFiles = Directory.GetFiles(chunkDir, "chunk_*.mp3")
                                      .OrderBy(f => f)
                                      .ToList();

            if (chunkFiles.Count == 0)
            {
                LogWarnBoth($"[TranscriptionService] ❌ No audio chunks generated by FFmpeg in '{chunkDir}'.");
                return (false, "No audio chunks were generated by FFmpeg.", null);
            }

            LogBoth($"[TranscriptionService] 📦 Generated {chunkFiles.Count} audio chunk(s) in '{chunkDir}'. Starting Groq Whisper transcription ({_groqModel})...");

            // 2. Transcribe each chunk using Groq Whisper API (max 3 retries per chunk)
            var chunkTexts = new List<string>();
            var httpClient = _httpClientFactory.CreateClient();
            httpClient.Timeout = TimeSpan.FromMinutes(5);

            bool hadChunkFailure = false;

            for (int i = 0; i < chunkFiles.Count; i++)
            {
                if (cancellationToken.IsCancellationRequested) break;

                var chunkPath = chunkFiles[i];
                var chunkName = Path.GetFileName(chunkPath);
                var chunkInfo = new FileInfo(chunkPath);
                double sizeKb = chunkInfo.Exists ? chunkInfo.Length / 1024.0 : 0;

                LogBoth($"[TranscriptionService] 🎙️ Processing chunk {i + 1}/{chunkFiles.Count} ('{chunkName}', {sizeKb:F1} KB)...");

                var (chunkSuccess, text) = await TranscribeSingleChunkWithRetryAsync(
                    httpClient,
                    chunkPath,
                    i + 1,
                    chunkFiles.Count,
                    cancellationToken,
                    maxRetries: 3
                );

                if (!chunkSuccess)
                {
                    LogWarnBoth($"[TranscriptionService] 🛑 Chunk {i + 1}/{chunkFiles.Count} ('{chunkName}') FAILED after 3 attempts. Stopping further chunk processing and discarding remaining chunks per fail-safe policy.");
                    hadChunkFailure = true;

                    // Delete remaining unprocessed chunks to free disk space immediately
                    for (int j = i; j < chunkFiles.Count; j++)
                    {
                        try { if (File.Exists(chunkFiles[j])) File.Delete(chunkFiles[j]); } catch { }
                    }
                    break;
                }

                if (string.IsNullOrWhiteSpace(text))
                {
                    LogWarnBoth($"[TranscriptionService] ℹ️ Chunk {i + 1}/{chunkFiles.Count} produced no recognized speech or was silent.");
                }
                else
                {
                    LogBoth($"[TranscriptionService] 📥 Chunk {i + 1}/{chunkFiles.Count} transcribed successfully ({text.Trim().Length} chars).");
                    chunkTexts.Add(text.Trim());
                }
            }

            // If even the first chunk failed and 0 chunks were processed, we cannot mark completed
            if (hadChunkFailure && chunkTexts.Count == 0)
            {
                LogWarnBoth($"[TranscriptionService] ❌ No audio chunks could be processed (first chunk failed after 3 tries). Recording cannot be completed.");
                return (false, "First audio chunk failed after 3 attempts.", null);
            }

            // 3. Combine text and save transcript file
            string fullTranscript;
            if (chunkTexts.Count > 0)
            {
                fullTranscript = string.Join("\n\n", chunkTexts).Trim();
                if (hadChunkFailure)
                {
                    fullTranscript += "\n\n[Note: Audio transcription ended early due to an unrecoverable service error in subsequent segments.]";
                    LogBoth($"[TranscriptionService] ⚠️ Partial transcript created from {chunkTexts.Count} successfully processed chunk(s). Marking job COMPLETED on table.");
                }
            }
            else
            {
                fullTranscript = "[No speech or audio detected in this recording]";
            }

            await File.WriteAllTextAsync(transcriptAbsolutePath, fullTranscript, Encoding.UTF8, cancellationToken);
            LogBoth($"[TranscriptionService] 📝 Transcript saved successfully to: '{transcriptAbsolutePath}' ({fullTranscript.Length} chars).");

            // 4. Safely delete original heavy .webm video ONLY after transcript is saved
            try
            {
                if (File.Exists(videoAbsolutePath))
                {
                    File.Delete(videoAbsolutePath);
                    LogBoth($"[TranscriptionService] 🗑️ Deleted original video '{Path.GetFileName(videoAbsolutePath)}' to reclaim disk space.");
                }
            }
            catch (Exception ex)
            {
                LogWarnBoth($"[TranscriptionService] Non-fatal error deleting original video: {ex.Message}");
            }

            return (true, hadChunkFailure
                ? "Transcription completed partially with successfully processed chunks."
                : "Transcription completed successfully.", transcriptRelativePath);
        }
        catch (Exception ex)
        {
            LogWarnBoth($"[TranscriptionService] ❌ Exception during transcription for RecordId '{recordId}': {ex.Message}");
            return (false, ex.Message, null);
        }
        finally
        {
            // 5. Job-owned cleanup of this isolated chunk directory
            try
            {
                if (Directory.Exists(chunkDir))
                {
                    Directory.Delete(chunkDir, recursive: true);
                }
            }
            catch { }
        }
    }

    private async Task<bool> SplitAudioWithFfmpegAsync(string videoPath, string chunkDir, CancellationToken cancellationToken)
    {
        var sw = Stopwatch.StartNew();
        try
        {
            Directory.CreateDirectory(chunkDir);
            var outputPattern = Path.Combine(chunkDir, "chunk_%03d.mp3");

            // Segment into 10-min (600s) mono 16kHz MP3 chunks (~2.4 MB each)
            var arguments = $"-y -i \"{videoPath}\" -vn -ac 1 -ar 16000 -c:a libmp3lame -b:a 32k -f segment -segment_time 600 \"{outputPattern}\"";

            var ffmpegExecutable = ResolveFfmpegBinaryPath();
            LogBoth($"[TranscriptionService] 🎬 Using FFmpeg executable: '{ffmpegExecutable}'");
            LogBoth($"[TranscriptionService] ⚙️ FFmpeg arguments: {arguments}");

            var psi = new ProcessStartInfo
            {
                FileName = ffmpegExecutable,
                Arguments = arguments,
                CreateNoWindow = true,
                UseShellExecute = false,
                RedirectStandardError = true,
                RedirectStandardOutput = true
            };

            using var process = Process.Start(psi);
            if (process == null)
            {
                LogWarnBoth("[TranscriptionService] ❌ Could not start FFmpeg process. Is 'ffmpeg' installed on the machine?");
                return false;
            }

            LogBoth($"[TranscriptionService] ⏳ FFmpeg process started (PID {process.Id}). Draining output streams to avoid pipe buffer deadlock...");

            // IMPORTANT: Asynchronously read stderr and stdout before/during wait to prevent OS pipe buffer deadlock
            var stderrTask = process.StandardError.ReadToEndAsync(cancellationToken);
            var stdoutTask = process.StandardOutput.ReadToEndAsync(cancellationToken);

            await process.WaitForExitAsync(cancellationToken);
            var stderr = await stderrTask;
            var stdout = await stdoutTask;
            sw.Stop();

            if (process.ExitCode != 0)
            {
                LogWarnBoth($"[TranscriptionService] ❌ FFmpeg exited with non-zero code {process.ExitCode} in {sw.ElapsedMilliseconds}ms.\nStderr: {stderr}\nStdout: {stdout}");
                return false;
            }

            LogBoth($"[TranscriptionService] ✅ FFmpeg completed successfully in {sw.ElapsedMilliseconds}ms (ExitCode 0).");
            return true;
        }
        catch (Exception ex)
        {
            sw.Stop();
            LogWarnBoth($"[TranscriptionService] ❌ Exception running FFmpeg in {sw.ElapsedMilliseconds}ms: {ex.Message}\nStack: {ex.StackTrace}");
            return false;
        }
    }

    private string ResolveFfmpegBinaryPath()
    {
        // 1. Check explicit configuration if provided
        var configPath = _config["Groq:FFmpegPath"];
        if (!string.IsNullOrWhiteSpace(configPath) && File.Exists(configPath))
        {
            LogBoth($"[TranscriptionService] 🔍 Found FFmpeg from config: '{configPath}'");
            return configPath;
        }

        try
        {
            var userProfile = Environment.GetFolderPath(Environment.SpecialFolder.UserProfile);
            var localAppData = Environment.GetFolderPath(Environment.SpecialFolder.LocalApplicationData);
            var programFiles = Environment.GetFolderPath(Environment.SpecialFolder.ProgramFiles);

            // 2. Common WinGet package paths (winget install Gyan.FFmpeg)
            var wingetPackagesDir = Path.Combine(localAppData, @"Microsoft\WinGet\Packages");
            if (Directory.Exists(wingetPackagesDir))
            {
                var wingetMatch = Directory.GetFiles(wingetPackagesDir, "ffmpeg.exe", SearchOption.AllDirectories).FirstOrDefault();
                if (!string.IsNullOrWhiteSpace(wingetMatch) && File.Exists(wingetMatch))
                {
                    LogBoth($"[TranscriptionService] 🔍 Found FFmpeg in WinGet packages: '{wingetMatch}'");
                    return wingetMatch;
                }
            }

            // 3. Known installation paths across Windows
            var candidatePaths = new[]
            {
                Path.Combine(localAppData, @"Microsoft\WinGet\Links\ffmpeg.exe"),
                @"C:\ProgramData\chocolatey\bin\ffmpeg.exe",
                Path.Combine(userProfile, @"scoop\shims\ffmpeg.exe"),
                Path.Combine(programFiles, @"ffmpeg\bin\ffmpeg.exe"),
                Path.Combine(programFiles, @"ffmpeg\ffmpeg.exe"),
                @"C:\ffmpeg\bin\ffmpeg.exe",
                @"C:\ffmpeg\ffmpeg.exe",
                Path.Combine(userProfile, @"ffmpeg\bin\ffmpeg.exe"),
                Path.Combine(userProfile, @"ffmpeg\ffmpeg.exe"),
                Path.Combine(localAppData, @"ffmpeg\bin\ffmpeg.exe")
            };

            foreach (var candidate in candidatePaths)
            {
                if (File.Exists(candidate))
                {
                    LogBoth($"[TranscriptionService] 🔍 Found FFmpeg at known path: '{candidate}'");
                    return candidate;
                }
            }

            // 4. Read latest PATH directly from Windows Registry (Machine + User)
            // (running terminal processes do not inherit PATH changes made after launch)
            var machinePath = Environment.GetEnvironmentVariable("PATH", EnvironmentVariableTarget.Machine) ?? "";
            var userPath = Environment.GetEnvironmentVariable("PATH", EnvironmentVariableTarget.User) ?? "";
            var processPath = Environment.GetEnvironmentVariable("PATH", EnvironmentVariableTarget.Process) ?? "";

            var allDirs = (machinePath + ";" + userPath + ";" + processPath)
                .Split(';', StringSplitOptions.RemoveEmptyEntries | StringSplitOptions.TrimEntries)
                .Distinct(StringComparer.OrdinalIgnoreCase);

            foreach (var dir in allDirs)
            {
                try
                {
                    var exePath = Path.Combine(dir, "ffmpeg.exe");
                    if (File.Exists(exePath))
                    {
                        LogBoth($"[TranscriptionService] 🔍 Found FFmpeg in Registry PATH: '{exePath}'");
                        return exePath;
                    }
                }
                catch { }
            }
        }
        catch (Exception ex)
        {
            LogWarnBoth($"[TranscriptionService] FFmpeg discovery error: {ex.Message}");
        }

        return "ffmpeg";
    }

    private async Task<(bool success, string? text)> TranscribeSingleChunkWithRetryAsync(
        HttpClient httpClient,
        string chunkPath,
        int chunkIndex,
        int totalChunks,
        CancellationToken cancellationToken,
        int maxRetries = 3)
    {
        var chunkName = Path.GetFileName(chunkPath);

        for (int attempt = 1; attempt <= maxRetries; attempt++)
        {
            var sw = Stopwatch.StartNew();
            try
            {
                var fileBytes = await File.ReadAllBytesAsync(chunkPath, cancellationToken);
                double sizeKb = fileBytes.Length / 1024.0;

                LogBoth($"[TranscriptionService] 📤 [Chunk {chunkIndex}/{totalChunks} | Attempt {attempt}/{maxRetries}] Preparing payload for '{chunkName}' ({sizeKb:F1} KB)...");

                using var request = new HttpRequestMessage(HttpMethod.Post, _groqApiUrl);
                request.Headers.Authorization = new AuthenticationHeaderValue("Bearer", _groqApiKey);

                using var form = new MultipartFormDataContent();

                var fileContent = new ByteArrayContent(fileBytes);
                fileContent.Headers.ContentType = new MediaTypeHeaderValue("audio/mpeg");

                form.Add(fileContent, "file", chunkName);
                form.Add(new StringContent(_groqModel), "model");
                form.Add(new StringContent("text"), "response_format");

                if (!string.IsNullOrWhiteSpace(_groqPrompt))
                {
                    form.Add(new StringContent(_groqPrompt), "prompt");
                }

                request.Content = form;

                LogBoth($"[TranscriptionService] 📡 [Chunk {chunkIndex}/{totalChunks} | Attempt {attempt}/{maxRetries}] Sending {sizeKb:F1} KB to Groq Whisper ({_groqModel}) at '{_groqApiUrl}'...");

                var response = await httpClient.SendAsync(request, cancellationToken);
                sw.Stop();

                if (response.IsSuccessStatusCode)
                {
                    var resultText = await response.Content.ReadAsStringAsync(cancellationToken);
                    LogBoth($"[TranscriptionService] ✅ [Chunk {chunkIndex}/{totalChunks} | Attempt {attempt}/{maxRetries}] Groq HTTP 200 OK received in {sw.ElapsedMilliseconds}ms! Result length: {resultText?.Length ?? 0} chars.");
                    return (true, resultText);
                }

                var errorBody = await response.Content.ReadAsStringAsync(cancellationToken);
                var statusCode = (int)response.StatusCode;

                LogWarnBoth($"[TranscriptionService] ❌ [Chunk {chunkIndex}/{totalChunks} | Attempt {attempt}/{maxRetries}] Groq returned HTTP {statusCode} ({response.ReasonPhrase}) in {sw.ElapsedMilliseconds}ms.\nFull Error Response: {errorBody}");

                // Handle Groq rate limit HTTP 429
                if (statusCode == 429)
                {
                    int delaySeconds = 60 * attempt;
                    LogWarnBoth($"[TranscriptionService] ⏳ Groq Rate Limit (429) hit. Backing off for {delaySeconds}s before Attempt {attempt + 1}/{maxRetries}...");
                    if (attempt < maxRetries)
                    {
                        await Task.Delay(TimeSpan.FromSeconds(delaySeconds), cancellationToken);
                    }
                    continue;
                }

                if (attempt < maxRetries)
                {
                    int delaySeconds = 5 * attempt;
                    LogWarnBoth($"[TranscriptionService] ⏳ Waiting {delaySeconds}s before retrying chunk {chunkIndex} (Attempt {attempt + 1}/{maxRetries})...");
                    await Task.Delay(TimeSpan.FromSeconds(delaySeconds), cancellationToken);
                }
            }
            catch (Exception ex)
            {
                sw.Stop();
                LogWarnBoth($"[TranscriptionService] 💥 [Chunk {chunkIndex}/{totalChunks} | Attempt {attempt}/{maxRetries}] Exception during Groq request in {sw.ElapsedMilliseconds}ms: {ex.GetType().Name} - {ex.Message}\nStack: {ex.StackTrace}");
                if (attempt < maxRetries)
                {
                    int delaySeconds = 5 * attempt;
                    LogWarnBoth($"[TranscriptionService] ⏳ Waiting {delaySeconds}s before retrying chunk {chunkIndex} (Attempt {attempt + 1}/{maxRetries})...");
                    await Task.Delay(TimeSpan.FromSeconds(delaySeconds), cancellationToken);
                }
            }
        }

        LogWarnBoth($"[TranscriptionService] 🛑 [Chunk {chunkIndex}/{totalChunks}] Exhausted all {maxRetries} attempts without success.");
        return (false, null);
    }

    public async Task<(bool success, string? content)> ReadTranscriptContentAsync(string transcriptRelativePath)
    {
        try
        {
            var storageDir = GetAbsoluteStorageDirectory();
            var fileName = Path.GetFileName(transcriptRelativePath);
            var absolutePath = Path.Combine(storageDir, fileName);

            if (!File.Exists(absolutePath))
            {
                // Try direct relative path
                var direct = Path.GetFullPath(Path.Combine(Directory.GetCurrentDirectory(), transcriptRelativePath));
                if (File.Exists(direct))
                {
                    absolutePath = direct;
                }
                else
                {
                    return (false, null);
                }
            }

            var text = await File.ReadAllTextAsync(absolutePath, Encoding.UTF8);
            return (true, text);
        }
        catch (Exception ex)
        {
            LogWarnBoth($"[TranscriptionService] Error reading transcript '{transcriptRelativePath}': {ex.Message}");
            return (false, null);
        }
    }

    private string GetAbsoluteStorageDirectory()
    {
        var rawPath = _recordingStoragePath;
        var absolutePath = Path.GetFullPath(Path.IsPathRooted(rawPath)
            ? rawPath
            : Path.Combine(Directory.GetCurrentDirectory(), rawPath));

        if (!Directory.Exists(absolutePath))
        {
            Directory.CreateDirectory(absolutePath);
        }

        return absolutePath;
    }
}
